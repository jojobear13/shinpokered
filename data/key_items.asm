MACRO key_item_bits
_bit = 0
_byte = 0
REPT _NARG
_byte = _byte | ((\1) << _bit)
_bit = _bit + 1
IF _bit == 8
	db _byte
_byte = 0
_bit = 0
ENDC
SHIFT
ENDR
IF _bit > 0
	db _byte
ENDC
ENDM

