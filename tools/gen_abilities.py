#!/usr/bin/env python3
"""Writes constants/ability_constants.asm, data/mon_abilities.asm,
data/ability_names.asm and data/move_flags.asm from PokeAPI's CSVs
(abilities.csv, pokemon_abilities.csv and move_flag_map.csv from https://github.com/PokeAPI/pokeapi/tree/master/data/v2/csv).

Usage: tools/gen_abilities.py <csv dir> <repo root>
"""
import csv, collections, re, sys
src, repo = sys.argv[1], sys.argv[2]
UNWORKABLE = {  # need weather, held items, infatuation or the Steel type
    "chlorophyll", "swift-swim", "sand-veil", "cloud-nine", "leaf-guard", "hydration",
    "cute-charm", "sticky-hold", "pickup", "magnet-pull"}
NAMES = {"lightning-rod": "LIGHTNINGROD", "compound-eyes": "COMPOUNDEYES",
         "neutralizing-gas": "NEUTRAL. GAS"}
ab = {int(r["id"]): r["identifier"] for r in csv.DictReader(open(f"{src}/abilities.csv"))}
slots = collections.defaultdict(dict)
for r in csv.DictReader(open(f"{src}/pokemon_abilities.csv")):
    if int(r["pokemon_id"]) <= 151 and r["is_hidden"] == "0":
        slots[int(r["pokemon_id"])][int(r["slot"])] = int(r["ability_id"])
used = sorted({a for s in slots.values() for a in s.values() if ab[a] not in UNWORKABLE})
const = lambda a: ab[a].upper().replace("-", "_") if a else "NO_ABILITY"

with open(f"{repo}/constants/ability_constants.asm", "w") as f:
    f.write("; abilities (the ones Gen 1's species have that work without weather,\n"
            "; held items, infatuation or the Steel type), in PokeAPI's order\n"
            "; generated by tools/gen_abilities.py from PokeAPI's data\n"
            "\tconst_def\n\tconst NO_ABILITY ; $00\n")
    for i, a in enumerate(used, 1):
        f.write(f"\tconst {const(a):<17}; ${i:02X}\n")
    f.write("NUM_ABILITIES EQU const_value - 1\n\n"
            "; bits of a move's flags (data/move_flags.asm)\n"
            "MOVE_CONTACT_F EQU 0\nMOVE_PUNCH_F   EQU 1\nMOVE_SOUND_F   EQU 2\n")

with open(f"{repo}/data/ability_names.asm", "w") as f:
    f.write("AbilityNames: ; in the order of the ability constants\n\tdb \"NO ABILITY@\"\n")
    for a in used:
        name = NAMES.get(ab[a], ab[a].upper().replace("-", " "))
        assert len(name) <= 12, name
        f.write(f'\tdb "{name}@"\n')

dex = {}
for line in open(f"{repo}/constants/pokedex_constants.asm"):
    m = re.match(r"\s*const DEX_(\w+)\s*; (\d+)", line)
    if m: dex[m.group(1)] = int(m.group(2))
dex["FARFETCH_D"] = dex["FARFETCHD"]
species = []
for line in open(f"{repo}/constants/pokemon_constants.asm"):
    m = re.match(r"\s*const (\w+)\s*; \$([0-9A-F]{2})", line)
    if m: species.append(m.group(1))
with open(f"{repo}/data/mon_abilities.asm", "w") as f:
    f.write("; each species' two abilities, by species index; the ability slot bit (bit 0\n"
            "; of the third DV byte) picks one. A species with one ability has it twice.\n"
            "; Abilities that need weather, held items, infatuation or the Steel type are\n"
            "; NO_ABILITY until those exist. Generated by tools/gen_abilities.py (non-hidden slots).\n"
            "MonAbilities:\n")
    for name in species:
        p = dex.get(name)
        if p is None:
            pair = (0, 0)
        else:
            s = slots[p]
            pair = (s[1], s.get(2, s[1]))
            pair = tuple(a if ab[a] not in UNWORKABLE else 0 for a in pair)
        f.write(f"\tdb {const(pair[0])+',':<18}{const(pair[1]):<17}; {name}\n")
    f.write("MonAbilitiesEnd:\n")
print(len(used), "abilities,", len(species), "species")

# PokeAPI's move ids 1-165 are Gen 1's, in the same order
FLAGS = {1: "MOVE_CONTACT_F", 8: "MOVE_PUNCH_F", 9: "MOVE_SOUND_F"}
move_flags = collections.defaultdict(list)
for r in csv.DictReader(open(f"{src}/move_flag_map.csv")):
    if int(r["move_id"]) <= 165 and int(r["move_flag_id"]) in FLAGS:
        move_flags[int(r["move_id"])].append(FLAGS[int(r["move_flag_id"])])
moves = []
for line in open(f"{repo}/constants/move_constants.asm"):
    m = re.match(r"\s*const (\w+)", line)
    if m: moves.append(m.group(1))  # STRUGGLE (165) follows NUM_ATTACKS
with open(f"{repo}/data/move_flags.asm", "w") as f:
    f.write("; each move's flags, from Gen 9: makes contact, is a punch, is a sound.\n"
            "; Generated by tools/gen_abilities.py.\n"
            "MoveFlags:\n")
    for i, name in enumerate(moves[:165], 1):
        bits = " | ".join(f"1 << {b}" for b in sorted(move_flags[i])) or "0"
        f.write(f"\tdb {bits:<40}; {name}\n")
    f.write("MoveFlagsEnd:\n")
