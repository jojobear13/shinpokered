#!/usr/bin/env python3
"""Writes data/item_pockets.asm: the bag's pockets (ItemPockets, one byte per
item id) and the order the bag keeps (ItemSortList: the pockets in order,
each item in its place within its pocket). The bag is sorted by it when the
bag screen opens, which shows one pocket at a time. TMs and HMs aren't in the
bag (they're owned, not carried: wTMsOwned).

Usage: tools/gen_item_pockets.py <repo root>
"""
import re, sys
repo = sys.argv[1]

POCKETS = [  # (constant, the items in their order)
    ("POCKET_ITEMS", """REPEL SUPER_REPEL MAX_REPEL ESCAPE_ROPE POKE_DOLL
        LEAF_STONE FIRE_STONE THUNDER_STONE WATER_STONE MOON_STONE MIST_STONE
        NUGGET DOME_FOSSIL HELIX_FOSSIL OLD_AMBER
        LEFTOVERS QUICK_CLAW KINGS_ROCK SCOPE_LENS BRIGHTPOWDER FOCUS_BAND FOCUS_SASH
        CHOICE_BAND CHOICE_SPECS CHOICE_SCARF LIFE_ORB EVIOLITE
        LIGHT_BALL THICK_CLUB METAL_POWDER STICK LUCKY_PUNCH
        LUCKY_EGG AMULET_COIN EVERSTONE EXP_SHARE SMOKE_BALL CLEANSE_TAG
        PINK_BOW BLACK_BELT SHARP_BEAK POISON_BARB SOFT_SAND HARD_STONE SILVERPOWDER
        SPELL_TAG METAL_COAT CHARCOAL MYSTIC_WATER MIRACLE_SEED MAGNET TWISTEDSPOON
        NEVERMELTICE DRAGON_FANG BLACKGLASSES FAIRYFEATHER"""),
    ("POCKET_MEDICINE", """POTION SUPER_POTION HYPER_POTION MAX_POTION FULL_RESTORE
        FRESH_WATER SODA_POP LEMONADE ANTIDOTE BURN_HEAL ICE_HEAL AWAKENING PARLYZ_HEAL
        FULL_HEAL REVIVE MAX_REVIVE ETHER MAX_ETHER ELIXER MAX_ELIXER
        HP_UP PROTEIN IRON CALCIUM ZINC CARBOS PP_UP RARE_CANDY M_GENE"""),
    ("POCKET_BALLS", "POKE_BALL GREAT_BALL ULTRA_BALL MASTER_BALL SAFARI_BALL"),
    ("POCKET_BATTLE", "X_ATTACK X_DEFEND X_SPEED X_SPECIAL X_ACCURACY DIRE_HIT GUARD_SPEC"),
    ("POCKET_BERRIES", """BERRY GOLD_BERRY SITRUS_BERRY PRZCUREBERRY MINT_BERRY PSNCUREBERRY
        ICE_BERRY BURNT_BERRY BITTER_BERRY MIRACLEBERRY MYSTERYBERRY"""),
    ("POCKET_KEY", """BICYCLE TOWN_MAP ITEMFINDER OLD_ROD GOOD_ROD SUPER_ROD SURFBOARD POKE_FLUTE
        EXP_ALL COIN_CASE S_S_TICKET SILPH_SCOPE SECRET_KEY LIFT_KEY CARD_KEY
        GOLD_TEETH BIKE_VOUCHER OAKS_PARCEL POKEDEX"""),
]
NEVER_HELD = re.compile(r"BADGE$|^FLOOR_|^COIN$|^PP_UP_2$")

ids = {}
for line in open(f"{repo}/constants/item_constants.asm"):
    m = re.match(r"\s*const (\w+)\s*; \$([0-9A-Fa-f]+)", line)
    if m:
        ids[m.group(1)] = int(m.group(2), 16)
last = max(v for k, v in ids.items() if not k.startswith(("TM_", "HM_")) and v < 0xC4)
pocket_of = {}
for p, (const, items) in enumerate(POCKETS):
    for item in items.split():
        assert item in ids, item
        assert ids[item] not in pocket_of, item
        pocket_of[ids[item]] = p
for name, i in ids.items():
    if i <= last and not NEVER_HELD.search(name):
        assert i in pocket_of, f"{name} has no pocket"

with open(f"{repo}/data/item_pockets.asm", "w") as f:
    f.write("; Generated by tools/gen_item_pockets.py.\n\n"
            "; each item's pocket\nItemPockets:\n")
    names = {v: k for k, v in ids.items() if k not in ("PP_UP_2",)}
    for i in range(1, last + 1):
        f.write(f"\tdb {POCKETS[pocket_of.get(i, 0)][0]:<15} ; {names.get(i, '?')}\n")
    f.write(f"ItemPocketsEnd:\n\tASSERT ItemPocketsEnd - ItemPockets == {names[last]}\n\n")
    f.write("; the bag's order: the pockets in order, each item in its place\nItemSortList::\n")
    for const, items in POCKETS:
        f.write(f"\t; {const}\n")
        for item in items.split():
            f.write(f"\tdb {item}\n")
    f.write("\tdb $FF ; end\n")
print(len(POCKETS), "pockets,", len(pocket_of), "items")
