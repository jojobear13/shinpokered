#!/usr/bin/env python3
"""Writes Gen 9's base stats and catch rates into data/baseStats/*.asm, and data/ev_yields.asm
and data/base_exp.asm and data/low_kick_powers.asm (by Pokédex number), from PokeAPI's CSVs
(pokemon_stats.csv, pokemon.csv and pokemon_species.csv from
https://github.com/PokeAPI/pokeapi/tree/master/data/v2/csv).

Usage: tools/gen_species.py <csv dir> <repo root>
"""
import csv, glob, re, sys
src, repo = sys.argv[1], sys.argv[2]
STATS = {1: "hp", 2: "attack", 3: "defense", 4: "special attack", 5: "special defense", 6: "speed"}
base, effort = {}, {}
for r in csv.DictReader(open(f"{src}/pokemon_stats.csv")):
    mon, stat = int(r["pokemon_id"]), int(r["stat_id"])
    if mon <= 151 and stat in STATS:
        base.setdefault(mon, {})[STATS[stat]] = int(r["base_stat"])
        effort.setdefault(mon, {})[STATS[stat]] = int(r["effort"])
exp = {int(r["id"]): int(r["base_experience"]) for r in csv.DictReader(open(f"{src}/pokemon.csv"))
       if int(r["id"]) <= 151}
catch = {int(r["id"]): int(r["capture_rate"]) for r in csv.DictReader(open(f"{src}/pokemon_species.csv"))
         if int(r["id"]) <= 151}

dex = {}
for line in open(f"{repo}/constants/pokedex_constants.asm"):
    m = re.match(r"\s*const (DEX_\w+)\s*; (\d+)", line)
    if m:
        dex[m.group(1)] = int(m.group(2))
for path in sorted(glob.glob(f"{repo}/data/baseStats/*.asm")):
    text = open(path).read()
    m = re.search(r"^db (DEX_\w+)", text, re.M)
    if not m or m.group(1) not in dex:
        continue
    stats = base[dex[m.group(1)]]
    for name, value in stats.items():
        text, n = re.subn(rf"^db \d+ ; base {name}$", f"db {value} ; base {name}", text, flags=re.M)
        assert n == 1, (path, name)
    text, n = re.subn(r"^db \d+ ; catch rate$", f"db {catch[dex[m.group(1)]]} ; catch rate", text, flags=re.M)
    assert n == 1, path
    open(path, "w").write(text)

names = {v: k for k, v in dex.items()}
with open(f"{repo}/data/ev_yields.asm", "w") as f:
    f.write("; Gen 9's EV yields, by Pokédex number, two bits each: HP, Attack, Defense,\n"
            "; Speed in the first byte (high bits first), Special Attack and Special\n"
            "; Defense in the high nibble of the second. Generated by tools/gen_species.py.\n"
            "EVYields:\n")
    for n in range(1, 152):
        e = effort[n]
        b1 = e["hp"] << 6 | e["attack"] << 4 | e["defense"] << 2 | e["speed"]
        b2 = e["special attack"] << 6 | e["special defense"] << 4
        f.write(f"\tdb %{b1:08b}, %{b2:08b} ; {names[n][4:]}\n")
with open(f"{repo}/data/base_exp.asm", "w") as f:
    f.write("; Gen 9's base experience yields, by Pokédex number (some are over 255).\n"
            "; Generated by tools/gen_species.py.\nBaseExpYields:\n")
    for n in range(1, 152):
        f.write(f"\tdw {exp[n]} ; {names[n][4:]}\n")
weight = {int(r["id"]): int(r["weight"]) for r in csv.DictReader(open(f"{src}/pokemon.csv"))
          if int(r["id"]) <= 151}  # hectograms
with open(f"{repo}/data/low_kick_powers.asm", "w") as f:
    f.write("; Low Kick's power against each species, from its Gen 9 weight (under 10 kg\n"
            "; 20, 25 kg 40, 50 kg 60, 100 kg 80, 200 kg 100, else 120), by Pokédex\n"
            "; number. Generated by tools/gen_species.py.\nLowKickPowers:\n")
    for n in range(1, 152):
        power = next((p for limit, p in ((100, 20), (250, 40), (500, 60), (1000, 80), (2000, 100))
                      if weight[n] < limit), 120)
        f.write(f"\tdb {power} ; {names[n][4:]}, {weight[n] / 10:g} kg\n")
