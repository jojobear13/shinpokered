"""Writes the randomizer's tables for the game, from the built ROMs:
data/rando/intl_*.asm (Red, Blue, Blue-JP) and data/rando/jp_*.asm (the
Japanese Red and Green, with the original layouts): _consts (constants),
_gen (the generator's tables) and _run (the tables the game looks up).

    make && python3 tools/rando/gen_data.py

The formats, all read by engine/rando/*.asm:

  RANDO_NODES, RANDO_SLOTS, RANDO_LOCS, RANDO_START
  RandoAdjIndex   dw * (nodes + 1): byte offset of each node's edges in RandoAdj
  RandoAdj        dw to | code << 11: code 0 free, 1-29 needs atom code-1,
                  RANDO_WARP (31): leaving through slot 'to'
  RandoRevIndex / RandoRev: the same, reversed (code RANDO_WARP: 'to' is a
                  slot p whose arrival this node is; the way back is the
                  leave nodes of p's partner)
  RandoSlotKind   db per slot: 0 outside door, 1 inside door, 2 inside stairs
  RandoSlotArrive dw per slot
  RandoSlotLeave  dw, dw per slot (second $FFFF if none)
  RandoKindsIndex dw * (slots + 1) / RandoKinds dw slots: the area table
  RandoLocIndex   dw * (locs + 1) / RandoLocData: db atom+1 needed (0 none),
                  db flags (bit 0: may hold a key item), db vanilla item, dw nodes
  RandoEvents     db atom, db count, dw nodes ... ; db $ff
  RandoGoal       db count, dw nodes
  RandoProgItems  db the progression items, in atom order
  RandoKeyItems   db the key items (KEY_ITEMS order), $ff
  RandoSlotWarp   db map, db warp per slot (where arriving through it puts you)
  RandoMapWarps   dw per map: 0, or a list of dw slot per warp ($ffff: stays)
  RandoBallLocs   db map, db sprite, db loc ... ; db $ff
  RandoHiddenLocs db loc per HiddenItemCoords entry ($ff: not shuffled)
  RandoMartPool   db items ... ; db $ff
"""
import os
import sys
sys.path.insert(0, os.path.dirname(__file__))
from graph import Graph
import logic as L
from regions import Regions, Compact
import randomizer as RZ
from rom import REPO

WARP = 31
# atoms, in bit order: the badges first (as wObtainedBadges), the events,
# the progression items, then what follows from them
ATOMS = (L.BADGES + ['BILL', 'CAPTAIN', 'FUJI', 'SILPH', 'DRINK'] + L.PROGRESSION +
         ['CUT', 'SURF', 'STRENGTH', 'BADGES7', 'BADGES8'])
assert len(ATOMS) <= 30


def atom_code(req):
    req = set(req)
    if not req:
        return 0
    assert len(req) == 1, req
    a, = req
    return ATOMS.index(a) + 1


class Tables:
    def __init__(self, rom_name):
        self.g = g = Graph(rom_name, logic=L)
        self.C = C = Compact(Regions(g))
        self.Rz = RZ.Randomizer(C)
        self.slots = sorted(C.leave)                  # slot = rank of the entrance id
        self.slot_of = {e: i for i, e in enumerate(self.slots)}
        self.rom = g.rom

    def edges(self):
        """Forward and reverse adjacency, CHAMPION edges dropped (never open)."""
        C = self.C
        fwd = [[] for _ in range(C.n)]
        rev = [[] for _ in range(C.n)]
        for a, b, r in C.edges:
            if 'CHAMPION' in r:
                continue
            code = atom_code(r)
            fwd[a].append(b | code << 11)
            rev[b].append(a | code << 11)
        for e in self.slots:
            s = self.slot_of[e]
            for v in C.leave[e]:
                fwd[v].append(s | WARP << 11)
            rev[C.arrive[e]].append(s | WARP << 11)
        return [sorted(x) for x in fwd], [sorted(x) for x in rev]

    def write(self, base, label):
        """base_consts.asm; base_gen.asm, the generator's tables, with labels
        {RP}Name (included in both of its banks, each with its own RP);
        base_kinds.asm (the door shuffle's area table), base_rev.asm (the
        reversed graph, for the softlock check); base_run.asm (the tables
        the game looks things up in)."""
        C, g, rom = self.C, self.g, self.rom
        files = {'consts': [], 'gen': [], 'kinds': [], 'rev': [], 'run': []}
        cur = ['consts']
        w = lambda line: files[cur[0]].append(line)
        for f in files:
            files[f].append('; generated by tools/rando/gen_data.py from %s.gbc; do not edit' % label)
        w('DEF RANDO_NODES EQU %d' % C.n)
        w('DEF RANDO_SLOTS EQU %d' % len(self.slots))
        w('DEF RANDO_LOCS EQU %d' % len(C.locs))
        w('DEF RANDO_START EQU %d' % C.start)
        for i, a in enumerate(ATOMS):
            w('DEF RANDO_ATOM_%s EQU %d' % (a, i))
        w('DEF RANDO_NUM_ATOMS EQU %d' % len(ATOMS))
        w('DEF RANDO_NUM_PROG EQU %d' % len(L.PROGRESSION))
        w('DEF RANDO_NUM_KEY EQU %d' % len(L.KEY_ITEMS))
        fwd, rev = self.edges()

        def dw(vals):
            for i in range(0, len(vals), 12):
                w('\tdw ' + ', '.join('$%04x' % v for v in vals[i:i + 12]))

        def db(vals):
            for i in range(0, len(vals), 16):
                w('\tdb ' + ', '.join('$%02x' % v for v in vals[i:i + 16]))

        def csr(name, lists, size=2):
            off, idx = 0, []
            for x in lists:
                idx.append(off)
                off += size * len(x)
            idx.append(off)
            w('{RP}%sIndex:' % name)
            if size == 1:
                assert off < 256
                db(idx)
            else:
                dw(idx)
            w('{RP}%s:' % name)
            (db if size == 1 else dw)([v for x in lists for v in x])

        cur[0] = 'gen'
        csr('Adj', fwd)
        w('{RP}SlotKind:')
        db([0 if e in C.O else 1 if e in C.I else 2 for e in self.slots])
        # where one arrives through a slot is also where one leaves it from;
        # a few slots are left from a second node too
        w('{RP}SlotNode:')
        dw([C.leave[e][0] for e in self.slots])
        for e in self.slots:
            assert C.arrive[e] == C.leave[e][0] and len(C.leave[e]) <= 2
        w('{RP}SlotNode2:')
        dw([v for e in self.slots if len(C.leave[e]) == 2 for v in (self.slot_of[e], C.leave[e][1])] + [0xFFFF])
        # locations: req, flags, vanilla item; which are at each node
        w('{RP}LocInfo:')
        for l in C.locs:
            db([atom_code(l['req']), 1 if l['prog'] else 0, rom.items[l['item']]])
        at = [[] for _ in range(C.n)]
        for k, l in enumerate(C.locs):
            for v in l['nodes']:
                at[v].append(k)
        csr('NodeLocs', at, size=1)
        w('{RP}ReqLocs:')         # the locations that need something, and their nodes
        for k, l in enumerate(C.locs):
            if l['req']:
                db([k, len(l['nodes'])])
                dw(l['nodes'])
        db([0xFF])
        # for each atom: the nodes with an edge it opens
        src = [[] for _ in ATOMS]
        for v, lst in enumerate(fwd):
            for x in lst:
                code = x >> 11
                if 0 < code < WARP and v not in src[code - 1]:
                    src[code - 1].append(v)
        csr('AtomSrc', src)
        w('{RP}Events:')
        for a in ['BILL', 'CAPTAIN', 'FUJI', 'SILPH', 'DRINK'] + L.BADGES:
            db([ATOMS.index(a), len(C.events[a])])
            dw(C.events[a])
        db([0xFF])
        w('{RP}Goal:')
        db([len(C.goal)])
        dw(C.goal)
        w('{RP}ProgItems:')
        db([rom.items[x] for x in L.PROGRESSION])
        w('{RP}KeyItems:')
        db([rom.items[x] for x in L.KEY_ITEMS] + [0xFF])
        cur[0] = 'kinds'
        kinds = [[self.slot_of[x] for x in self.Rz.kinds[e]] for e in self.slots]
        csr('Kinds', kinds)
        # and the other way: for each slot, the slots whose areas it's in
        back = [[] for _ in self.slots]
        for s, lst in enumerate(kinds):
            for t in lst:
                back[t].append(s)
        csr('KindsBack', back)
        # marts (built when one opens, from the seed): for each, 0 if it keeps
        # its list, else how many it sells; what every one sells; the pool
        lists = RZ.mart_lists(rom)
        always, pool = RZ.mart_pool(rom, lists)
        w('RandoMartSizes::')
        db([0 if i in RZ.STATIC_MARTS else len(x) for i, x in enumerate(lists)])
        w('RandoMartAlways::')
        db(always)
        w('RandoMartPool::')
        db(pool)
        files['consts'].append('DEF RANDO_MARTS EQU %d' % len(lists))
        files['consts'].append('DEF RANDO_MART_ALWAYS EQU %d' % len(always))
        cur[0] = 'rev'
        csr('Rev', rev)
        # runtime: warps
        cur[0] = 'run'
        w('RandoSlotWarp::')
        sw = []
        for e in self.slots:
            mid, i = g.arrival[e]
            sw += [mid, i]
        db(sw)
        w('RandoMapWarps::')
        maps = {}
        for e in self.slots:
            for (mid, i) in g.entrances[e]:
                maps.setdefault(mid, {})[i] = self.slot_of[e]
        for m in range(256):
            w('\tdw %s' % ('RandoMapWarps%02X' % m if m in maps else '0'))
        for m in sorted(maps):
            w('RandoMapWarps%02X:' % m)
            n = len(g.w.maps[m]['warps'])
            dw([maps[m].get(i, 0xFFFF) for i in range(n)])
        w('RandoBallLocs::')
        bl = []
        for k, l in enumerate(C.locs):
            if l['key'][0] == 'ball':
                bl += [l['map'], l['key'][2], k]
        db(bl + [0xFF])
        w('RandoHiddenLocs::')
        coords = hidden_coords(rom)
        hl = []
        for (mid, y, x) in coords:
            k = [i for i, l in enumerate(C.locs) if l['key'][0] == 'hidden' and l['map'] == mid and
                 l['square'] == (x, y)]
            hl.append(k[0] if k else 0xFF)
        db(hl)
        for name in L.GIFTS:
            k = [i for i, l in enumerate(C.locs) if l['key'] == ('gift', name)][0]
            files['consts'].append('DEF RANDO_LOC_%s EQU %d' % (name, k))
        files['consts'].append('DEF RANDO_MART_POOL EQU %d' % len(pool))
        for f, lines in files.items():
            with open('%s_%s.asm' % (base, f), 'w') as out:
                out.write('\n'.join(lines) + '\n')


def hidden_coords(rom):
    bank, a = rom.at('HiddenItemCoords')
    out = []
    while rom.b(bank, a) != 0xFF:
        out.append(tuple(rom.b(bank, a, 3)))
        a += 3
    return out


if __name__ == '__main__':
    os.makedirs(os.path.join(REPO, 'data/rando'), exist_ok=True)
    for f in os.listdir(os.path.join(REPO, 'data/rando')):
        os.remove(os.path.join(REPO, 'data/rando', f))
    Tables('pokered').write(os.path.join(REPO, 'data/rando/intl'), 'pokered')
    Tables('pokeredjp').write(os.path.join(REPO, 'data/rando/jp'), 'pokeredjp')
