#!/usr/bin/env python3
"""Writes data/type_effects.asm (Gen 6+'s type chart) and each species' types
in data/baseStats/*.asm (Gen 9's) from PokeAPI's CSVs (types.csv,
type_efficacy.csv and pokemon_types.csv from
https://github.com/PokeAPI/pokeapi/tree/master/data/v2/csv).

Usage: tools/gen_types.py <csv dir> <repo root>
"""
import csv, glob, re, sys
src, repo = sys.argv[1], sys.argv[2]
names = {int(r["id"]): r["identifier"].upper() for r in csv.DictReader(open(f"{src}/types.csv"))
         if int(r["id"]) <= 18}
chart = [(int(r["damage_type_id"]), int(r["target_type_id"]), int(r["damage_factor"]))
         for r in csv.DictReader(open(f"{src}/type_efficacy.csv"))]
FACTOR = {0: "00", 50: "05", 200: "20"}
with open(f"{repo}/data/type_effects.asm", "w") as f:
    f.write("TypeEffects:\n"
            "; format: attacking type, defending type, damage multiplier\n"
            "; the multiplier is a (decimal) fixed-point number:\n"
            ";     20 is ×2.0\n;     05 is ×0.5\n;     00 is ×0\n"
            "; Gen 6+'s chart (with Steel, Dark and Fairy), generated by tools/gen_types.py\n"
            "; from PokeAPI's data. TYPELESS (Struggle's) has no entries: neutral to all.\n")
    for atk, dfn, factor in chart:
        if atk in names and dfn in names and factor != 100:
            f.write(f"\tdb {names[atk]},{names[dfn]},{FACTOR[factor]}\n")
    f.write("\tdb $FF\n")

dex = {}
for line in open(f"{repo}/constants/pokedex_constants.asm"):
    m = re.match(r"\s*const (DEX_\w+)\s*; (\d+)", line)
    if m:
        dex[m.group(1)] = int(m.group(2))
types = {}
for r in csv.DictReader(open(f"{src}/pokemon_types.csv")):
    types.setdefault(int(r["pokemon_id"]), {})[int(r["slot"])] = names[int(r["type_id"])]
changed = []
for path in sorted(glob.glob(f"{repo}/data/baseStats/*.asm")):
    text = open(path).read()
    m = re.search(r"^db (DEX_\w+)", text, re.M)
    if not m or m.group(1) not in dex:
        continue
    t = types[dex[m.group(1)]]
    t1, t2 = t[1], t.get(2, t[1])
    new = re.sub(r"^db \w+ ; species type 1\ndb \w+ ; species type 2",
                 f"db {t1} ; species type 1\ndb {t2} ; species type 2", text, flags=re.M)
    if new != text:
        changed.append(path.rsplit("/", 1)[1])
        open(path, "w").write(new)
print("types changed:", changed)
