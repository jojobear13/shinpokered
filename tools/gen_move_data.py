#!/usr/bin/env python3
"""Writes Gen 9's per-move data the Gen 1 move struct has no room for, from
PokeAPI's CSVs (moves.csv and move_meta.csv from
https://github.com/PokeAPI/pokeapi/tree/master/data/v2/csv):

  data/move_chances.asm     each move's secondary effect chance, out of 256
                            (0: the effect's own; 255: always)
  data/move_priorities.asm  the moves whose priority isn't 0
  data/move_crit_moves.asm  the moves with a higher critical hit ratio
  data/move_flags.asm       each move's flags (MOVE_*_F), from move_flag_map.csv
  data/move_categories.asm  each move's category (Struggle stays physical)
  data/moves.asm            power, type, accuracy and PP rewritten in place
                            (effects stay hand-written)

Moves are matched by id: the game's ids 1-165 are PokeAPI's.

Usage: tools/gen_move_data.py <csv dir> <repo root>
"""
import csv, re, sys
src, repo = sys.argv[1], sys.argv[2]
moves = {int(r["id"]): r for r in csv.DictReader(open(f"{src}/moves.csv"))}
meta = {int(r["move_id"]): r for r in csv.DictReader(open(f"{src}/move_meta.csv"))}
names = []
for line in open(f"{repo}/constants/move_constants.asm"):
    m = re.match(r"\s*const (\w+)\s*; \$?([0-9a-fA-F]+)", line)
    if m:
        names.append(m.group(1))
    if names and names[-1] == "STRUGGLE":
        break
ids = {name: i for i, name in enumerate(names, 1)}
POKEAPI = {}  # the game's move id -> PokeAPI's, for the moves added after Gen 1
extra = re.findall(r"^; pokeapi (\w+) (\d+)$", open(f"{repo}/constants/move_constants.asm").read(), re.M)
for name, pid in extra:
    POKEAPI[ids[name]] = int(pid)


def row(i):
    return moves[POKEAPI.get(i, i)], meta[POKEAPI.get(i, i)]


def chance(percent):
    return 255 if percent >= 100 else round(percent * 256 / 100)


with open(f"{repo}/data/move_chances.asm", "w") as f:
    f.write("; each move's Gen 9 secondary effect chance, out of 256 (0: the effect's own;\n"
            "; 255: always), by move id. Generated by tools/gen_move_data.py.\nMoveChances:\n")
    for i, name in enumerate(names, 1):
        m, mt = row(i)
        p = int(m["effect_chance"] or 0) or int(mt["flinch_chance"] or 0)
        f.write(f"\tdb {chance(p):3} ; {name}\n")
with open(f"{repo}/data/move_priorities.asm", "w") as f:
    f.write("; the moves whose Gen 9 priority isn't 0. Generated by tools/gen_move_data.py.\n"
            "MovePriorities:\n")
    for i, name in enumerate(names, 1):
        p = int(row(i)[0]["priority"])
        if p:
            f.write(f"\tdb {name}, {p}\n")
    f.write("\tdb 0\n")
with open(f"{repo}/data/move_crit_moves.asm", "w") as f:
    f.write("; the moves with a higher critical hit ratio (+1 stage in Gen 9). Generated by\n"
            "; tools/gen_move_data.py.\nHighCriticalMoves:\n")
    for i, name in enumerate(names, 1):
        if int(row(i)[1]["crit_rate"] or 0):
            f.write(f"\tdb {name}\n")
    f.write("\tdb $FF\n")

FLAGS = {1: "MOVE_CONTACT_F", 8: "MOVE_PUNCH_F", 9: "MOVE_SOUND_F", 7: "MOVE_MIRROR_F",
         11: "MOVE_DEFROST_F", 15: "MOVE_POWDER_F", 14: "MOVE_BYPASS_SUB_F"}
flags = {}
for r in csv.DictReader(open(f"{src}/move_flag_map.csv")):
    if int(r["move_flag_id"]) in FLAGS:
        flags.setdefault(int(r["move_id"]), []).append(FLAGS[int(r["move_flag_id"])])
with open(f"{repo}/data/move_flags.asm", "w") as f:
    f.write("; each move's flags (MOVE_*_F), from Gen 9: makes contact, is a punch, is a\n"
            "; sound, can be mirrored, thaws its user, is a powder, goes through a\n"
            "; substitute, never misses (no accuracy). Generated by tools/gen_move_data.py.\n"
            "MoveFlags:\n")
    for i, name in enumerate(names, 1):
        pid = POKEAPI.get(i, i)
        bits = sorted(flags.get(pid, []), key=lambda b: list(FLAGS.values()).index(b))
        if not row(i)[0]["accuracy"]:
            bits.append("MOVE_NEVER_MISS_F")
        f.write(f"\tdb {' | '.join(f'1 << {b}' for b in bits) or '0'} ; {name}\n")
    f.write("MoveFlagsEnd:\n")

# data/moves.asm: Gen 9's power, type, accuracy and PP for the moves with a
# PokeAPI row. Kept as they are: power where PokeAPI has none (fixed damage,
# OHKO and status moves: the engine reads 1 as "does damage"), Low Kick's
# nominal power (LowKickPower sets it by weight) and the typeless (BIRD)
# Struggle and Bide. No accuracy means it never misses (MOVE_NEVER_MISS_F):
# 100 here.
TYPES = {"normal": "NORMAL", "fighting": "FIGHTING", "flying": "FLYING", "poison": "POISON",
         "ground": "GROUND", "rock": "ROCK", "bug": "BUG", "ghost": "GHOST", "steel": "STEEL",
         "fire": "FIRE", "water": "WATER", "grass": "GRASS", "electric": "ELECTRIC",
         "psychic": "PSYCHIC", "ice": "ICE", "dragon": "DRAGON", "dark": "DARK", "fairy": "FAIRY"}
type_names = {int(r["id"]): r["identifier"] for r in csv.DictReader(open(f"{src}/types.csv"))}
path = f"{repo}/data/moves.asm"
out = []
for line in open(path):
    m = re.match(r"(\s*move )(\w+)(,\s*)(\w+)(,\s*)(\d+)(,\s*)(\w+)(,\s*)(\d+)(,\s*)(\d+)(.*)$", line.rstrip("\n"))
    if not m or m.group(2) not in ids:
        out.append(line)
        continue
    g = list(m.groups())
    name = g[1]
    r = row(ids[name])[0]
    if r["power"] and name != "LOW_KICK":
        g[5] = r["power"]
    if g[7] != "BIRD":
        g[7] = TYPES[type_names[int(r["type_id"])]]
    g[9] = r["accuracy"] or "100"
    g[11] = r["pp"]
    for i in (5, 9, 11):  # keep the columns: right-align in the old field's width
        width = len(m.group(i)) + len(m.group(i + 1)) - 1
        g[i - 1] = "," + " " * max(1, width - len(g[i]))
    out.append("".join(g) + "\n")
open(path, "w").write("".join(out))

CATEGORY = {"1": "STATUS", "2": "PHYSICAL", "3": "SPECIAL"}
with open(f"{repo}/data/move_categories.asm", "w") as f:
    f.write("; Each move's category, Gen 9's (Gen 4 introduced the physical/special split).\n"
            "; A move's category, not its type, decides whether it uses attack and defense\n"
            "; or special attack and special defense. Indexed by move id - 1; see\n"
            "; GetMoveCategory. Generated by tools/gen_move_data.py.\n"
            "MoveCategories:\n")
    for i, name in enumerate(names, 1):
        cat = "PHYSICAL" if name == "STRUGGLE" else CATEGORY[row(i)[0]["damage_class_id"]]
        f.write(f"\tdb {cat:<8} ; {name}\n")
    f.write("MoveCategoriesEnd:\n\tASSERT MoveCategoriesEnd - MoveCategories == STRUGGLE\n")
