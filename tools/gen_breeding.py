#!/usr/bin/env python3
"""Writes data/breeding.asm: what breeding needs per species, by Pokédex
number, from PokeAPI's CSVs (https://github.com/PokeAPI/pokeapi/tree/master/
data/v2/csv: pokemon_species.csv, pokemon_egg_groups.csv, pokemon_moves.csv).

- EggGroups: two egg groups (EGG_*; the same twice for one group)
- EggCycles: how many 256-step cycles its egg takes to hatch
- BaseForms: the species its eggs are (the first of its evolution line in
  the first 151)
- EggMovePointers: its egg moves: those of the first of its whole line (a
  later baby such as Pichu included). They're Scarlet and Violet's, or, for
  a species not in them, the latest game's that has them (Sword and Shield
  first), keeping only moves this game has.

Usage: tools/gen_breeding.py <csv dir> <repo root>
"""
import csv, re, sys
src, repo = sys.argv[1:]

# preferred version groups for egg moves: SV, SwSh, BDSP, then the rest, newest first
PREFERENCE = [25, 20, 23, 18, 17, 16, 15, 14, 11, 10, 8, 7, 6, 5, 4, 3]
EGG_GROUPS = {1: "EGG_MONSTER", 2: "EGG_WATER_1", 3: "EGG_BUG", 4: "EGG_FLYING", 5: "EGG_FIELD",
              6: "EGG_FAIRY", 7: "EGG_GRASS", 8: "EGG_HUMAN_LIKE", 9: "EGG_WATER_3", 10: "EGG_MINERAL",
              11: "EGG_AMORPHOUS", 12: "EGG_WATER_2", 13: "EGG_DITTO", 14: "EGG_DRAGON", 15: "EGG_NONE"}

dex = {}
for line in open(f"{repo}/constants/pokedex_constants.asm"):
    m = re.match(r"\s*const DEX_(\w+)\s*; (\d+)", line)
    if m:
        dex[int(m.group(2))] = m.group(1)
assert len(dex) == 151

# move ids: Gen 1's are PokeAPI's own; the new ones say theirs
moves = {}
for line in open(f"{repo}/constants/move_constants.asm"):
    m = re.match(r"\s*const (\w+)\s*; ([0-9a-f]{2})\b", line)
    if m and int(m.group(2), 16) <= 0xA4:
        moves[int(m.group(2), 16)] = m.group(1)
    m = re.match(r"; pokeapi (\w+) (\d+)", line)
    if m:
        moves[int(m.group(2))] = m.group(1)

species = {int(r["id"]): r for r in csv.DictReader(open(f"{src}/pokemon_species.csv"))}
groups = {}
for r in csv.DictReader(open(f"{src}/pokemon_egg_groups.csv")):
    if int(r["species_id"]) <= 151:
        groups.setdefault(int(r["species_id"]), []).append(int(r["egg_group_id"]))


def base_form(n, limit=151):
    while species[n]["evolves_from_species_id"] and int(species[n]["evolves_from_species_id"]) <= limit:
        n = int(species[n]["evolves_from_species_id"])
    return n


egg = {}  # (species, version group) -> moves in PokeAPI's order
for r in csv.DictReader(open(f"{src}/pokemon_moves.csv")):
    n = int(r["pokemon_id"])
    if n < 10000 and r["pokemon_move_method_id"] == "2":
        egg.setdefault((n, int(r["version_group_id"])), []).append(int(r["move_id"]))

out = ["; Generated by tools/gen_breeding.py from PokeAPI's data.", ""]
out.append("; each species' two egg groups, by Pokédex number")
out.append("EggGroups:")
for n in range(1, 152):
    g = sorted(groups[n]) * 2
    out.append(f"\tdb {EGG_GROUPS[g[0]]}, {EGG_GROUPS[g[1]]} ; {dex[n]}")
out.append("")
out.append("; how many 256-step cycles each species' egg takes to hatch")
out.append("EggCycles:")
for n in range(1, 152):
    out.append(f"\tdb {int(species[n]['hatch_counter'])} ; {dex[n]}")
out.append("")
out.append("; the species each species' eggs are (the first of its evolution line)")
out.append("BaseForms:")
for n in range(1, 152):
    out.append(f"\tdb {dex[base_form(n)]} ; {dex[n]}")
out.append("")
out.append("; each species' egg moves (its base form's), a list ending in 0")
out.append("EggMovePointers:")
lists = {}
for n in range(1, 152):
    b = base_form(n)
    first = base_form(n, limit=10000)
    vg = next((v for v in PREFERENCE if (first, v) in egg), None)
    ids = egg.get((first, vg), []) if vg else []
    lists[n] = [moves[i] for i in dict.fromkeys(ids) if i in moves]
    label = f"EggMoves{dex[b].title().replace('_', '')}" if lists[n] else "NoEggMoves"
    out.append(f"\tdw {label} ; {dex[n]}")
out.append("")
out.append("NoEggMoves:")
out.append("\tdb 0")
done = set()
for n in range(1, 152):
    b = base_form(n)
    if lists[n] and b not in done:
        done.add(b)
        out.append(f"EggMoves{dex[b].title().replace('_', '')}:")
        out.append("\tdb " + ", ".join(lists[n] + ["0"]))
open(f"{repo}/data/breeding.asm", "w").write("\n".join(out) + "\n")
print(len(done), "egg move lists")
