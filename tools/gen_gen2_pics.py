#!/usr/bin/env python3
"""Fetches Pokémon Crystal's front and back sprites for the first 151 from
pret's pokecrystal disassembly (https://github.com/pret/pokecrystal,
gfx/pokemon/<name>/front.png and back.png), and writes:

- pic/gen2mon/<name>.png: each front's first frame (its still pose; Crystal's
  fronts stack their animation frames below it), 40, 48 or 56 pixels square
- pic/gen2monback/<name>b.png: each back, 48x48 (shown unscaled, as the
  Spaceworld backs are)
- data/gen2_pics.asm: Gen2PicHeaders, by Pokédex number (the sprite size, the
  front and back pics and their bank), and a section per species holding its
  two pics, so the linker keeps each pair in one bank

The pictures are grey from pret's palette indices: 0 white, 1 light grey,
2 dark grey, 3 black, as this repo's pics are. The build compresses them
(tools/pkmncompress), as it does every pic.

Usage: tools/gen_gen2_pics.py <repo root> [<directory of downloaded PNGs>]
"""
import os, re, subprocess, sys
from PIL import Image

repo = sys.argv[1]
cache = sys.argv[2] if len(sys.argv) > 2 else None
URL = "https://raw.githubusercontent.com/pret/pokecrystal/master/gfx/pokemon/{}/{}"
PRET_NAMES = {"NIDORAN_F": "nidoran_f", "NIDORAN_M": "nidoran_m", "FARFETCHD": "farfetch_d", "MR_MIME": "mr__mime"}
GREYS = [255, 170, 85, 0]

dex = {}
for line in open(f"{repo}/constants/pokedex_constants.asm"):
    m = re.match(r"\s*const DEX_(\w+)\s*; (\d+)", line)
    if m:
        dex[int(m.group(2))] = m.group(1)
assert len(dex) == 151


def fetch(name, which):
    if cache:
        path = f"{cache}/{name}_{which}"
        if os.path.exists(path):
            return Image.open(path)
    tmp = f"/tmp/gen2_{name}_{which}"
    subprocess.run(["curl", "-sSfL", "-o", tmp, URL.format(name, which)], check=True)
    return Image.open(tmp)


def grey(im, size):
    assert im.mode == "P", im.mode
    out = Image.new("L", (size, size))
    for y in range(size):
        for x in range(size):
            out.putpixel((x, y), GREYS[im.getpixel((x, y))])
    return out


for d in ("gen2mon", "gen2monback"):
    os.makedirs(f"{repo}/pic/{d}", exist_ok=True)
lines = ["; Generated by tools/gen_gen2_pics.py from pret's pokecrystal (Crystal's sprites).", "",
         "; by Pokédex number: the front's size (as the base stats' byte), the front and",
         "; back pics, and their bank", "Gen2PicHeaders:"]
sections = []
for n in range(1, 152):
    name = PRET_NAMES.get(dex[n], dex[n].lower())
    front = fetch(name, "front.png")
    size = front.size[0]
    assert size in (40, 48, 56) and front.size[1] % size == 0, (name, front.size)
    grey(front, size).save(f"{repo}/pic/gen2mon/{name}.png")
    back = fetch(name, "back.png")
    assert back.size == (48, 48), (name, back.size)
    grey(back, 48).save(f"{repo}/pic/gen2monback/{name}b.png")
    label = "Gen2" + "".join(p.title() for p in name.split("_") if p)
    lines.append(f'\tdb BANK({label}Front) ; {dex[n]}')
    lines.append(f'\tINCBIN "pic/gen2mon/{name}.pic", 0, 1')
    lines.append(f"\tdw {label}Front, {label}Back")
    sections.append(f'SECTION "Gen 2 Pics {dex[n]}", ROMX\n'
                    f'{label}Front: INCBIN "pic/gen2mon/{name}.pic"\n'
                    f'{label}Back:  INCBIN "pic/gen2monback/{name}b.pic"\n')
lines.append("Gen2PicHeadersEnd:")
lines.append("ASSERT Gen2PicHeadersEnd - Gen2PicHeaders == NUM_POKEMON * GEN2_PIC_HEADER_LENGTH")
lines.append("")
open(f"{repo}/data/gen2_pics.asm", "w").write("\n".join(lines) + "\n\n" + "\n".join(sections))
print("151 fronts and backs")
